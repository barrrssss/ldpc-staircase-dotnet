using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using LdpcStaircase;
using Xunit;

namespace LdpcStaircase.Tests
{
    /// <summary>
    /// The cross-language conformance gate. Loads the canonical vectors from the spec submodule
    /// (<c>external/ldpc-staircase-spec/vectors/MANIFEST.json</c>) and asserts byte-exact
    /// agreement: every <c>*.bin</c> matches its recorded length and SHA-256, and every PRNG,
    /// matrix, encode, and decode case reproduces exactly.
    ///
    /// <para>The vectors are generated by <c>ldpc-staircase-java</c>. This suite passing is the
    /// standing proof that the two runtimes build the same graph and produce the same bytes —
    /// including the one place it could plausibly go wrong, the IEEE 754 scaling in
    /// <see cref="PmmsRandom.NextBounded"/>.</para>
    /// </summary>
    public sealed class ConformanceTests
    {
        private static readonly string VectorsDir = LocateVectorsDir();

        private static JsonElement Manifest => LoadManifestRoot();

        /// <summary>
        /// Walks up from the test assembly looking for
        /// <c>external/ldpc-staircase-spec/vectors/MANIFEST.json</c>. Returns the vectors
        /// directory, or null if not found.
        /// </summary>
        private static string LocateVectorsDir()
        {
            var dir = new DirectoryInfo(AppContext.BaseDirectory);
            while (dir != null)
            {
                string candidate = Path.Combine(
                    dir.FullName, "external", "ldpc-staircase-spec", "vectors", "MANIFEST.json");
                if (File.Exists(candidate))
                {
                    return Path.GetDirectoryName(candidate);
                }

                dir = dir.Parent;
            }

            return null;
        }

        private static JsonElement LoadManifestRoot()
        {
            Assert.True(VectorsDir != null,
                "Conformance vectors not found. Did the git submodule "
                + "(external/ldpc-staircase-spec) get initialized?");

            using var doc = JsonDocument.Parse(File.ReadAllText(Path.Combine(VectorsDir, "MANIFEST.json")));
            return doc.RootElement.Clone();
        }

        private static byte[] LoadBin(string relativePath)
        {
            return File.ReadAllBytes(Path.Combine(VectorsDir, relativePath));
        }

        private static string ToHex(byte[] bytes)
        {
            var sb = new StringBuilder(bytes.Length * 2);
            foreach (byte b in bytes)
            {
                sb.Append(b.ToString("x2", CultureInfo.InvariantCulture));
            }

            return sb.ToString();
        }

        private static string Sha256Hex(byte[] data)
        {
            using var sha = SHA256.Create();
            return ToHex(sha.ComputeHash(data));
        }

        private static int[] IntArray(JsonElement element)
        {
            return element.EnumerateArray().Select(e => e.GetInt32()).ToArray();
        }

        /// <summary>
        /// Maps the manifest's stage names — written by the Java enum, hence
        /// <c>SCREAMING_SNAKE_CASE</c> — onto <see cref="DecodeStage"/>.
        /// </summary>
        private static DecodeStage ParseStage(string name)
        {
            switch (name)
            {
                case "NONE": return DecodeStage.None;
                case "PEELING": return DecodeStage.Peeling;
                case "RESIDUAL_SOLVE": return DecodeStage.ResidualSolve;
                default: throw new InvalidOperationException("Unknown stage in manifest: " + name);
            }
        }

        [Fact]
        public void ManifestPresentAndWellFormed()
        {
            JsonElement root = Manifest;
            Assert.Equal(1, root.GetProperty("manifestVersion").GetInt32());
            foreach (string section in new[] { "prngRaw", "prngBounded", "matrix", "encode", "decode", "files" })
            {
                JsonElement value = root.GetProperty(section);
                Assert.Equal(JsonValueKind.Array, value.ValueKind);
                Assert.True(value.GetArrayLength() > 0, section + " section is empty");
            }
        }

        /// <summary>
        /// Every blob referenced in the manifest must have the listed byte length and SHA-256.
        /// This anchors the vectors as the byte-exact oracle.
        /// </summary>
        [Fact]
        public void FileDigestsMatch()
        {
            foreach (JsonElement file in Manifest.GetProperty("files").EnumerateArray())
            {
                string path = file.GetProperty("path").GetString();
                byte[] bytes = LoadBin(path);
                Assert.True(file.GetProperty("length").GetInt32() == bytes.Length,
                    "byte length mismatch for " + path);
                Assert.True(file.GetProperty("sha256").GetString() == Sha256Hex(bytes),
                    "SHA-256 mismatch for " + path);
            }
        }

        /// <summary>
        /// PRNG vectors: the raw Park-Miller stream at listed ordinals (SPEC.md section 3). A
        /// divergence here means every downstream matrix is wrong.
        /// </summary>
        [Fact]
        public void PrngRawVectorsMatch()
        {
            foreach (JsonElement testCase in Manifest.GetProperty("prngRaw").EnumerateArray())
            {
                string name = testCase.GetProperty("name").GetString();
                var rng = new PmmsRandom(testCase.GetProperty("seed").GetInt32());
                int position = 0;
                int value = 0;
                foreach (JsonElement expected in testCase.GetProperty("values").EnumerateArray())
                {
                    int ordinal = expected.GetProperty("ordinal").GetInt32();
                    while (position < ordinal)
                    {
                        value = rng.Next();
                        position++;
                    }

                    Assert.True(expected.GetProperty("value").GetInt32() == value,
                        $"{name}: value {ordinal} must match the manifest");
                }
            }
        }

        /// <summary>PRNG vectors: the bounded scaling of SPEC.md section 3.</summary>
        [Fact]
        public void PrngBoundedVectorsMatch()
        {
            foreach (JsonElement testCase in Manifest.GetProperty("prngBounded").EnumerateArray())
            {
                string name = testCase.GetProperty("name").GetString();
                var rng = new PmmsRandom(testCase.GetProperty("seed").GetInt32());
                int maxv = testCase.GetProperty("maxv").GetInt32();
                int[] expected = IntArray(testCase.GetProperty("draws"));
                var actual = new int[expected.Length];
                for (int i = 0; i < expected.Length; i++)
                {
                    actual[i] = rng.NextBounded(maxv);
                }

                Assert.True(expected.SequenceEqual(actual),
                    $"{name}: bounded draws must match the manifest "
                    + $"(expected [{string.Join(", ", expected)}], got [{string.Join(", ", actual)}])");
            }
        }

        /// <summary>
        /// Matrix vectors: rebuilding <c>H</c> from <c>(K, R, N1, seed)</c> must reproduce the
        /// committed canonical serialization exactly (SPEC.md sections 4 and 7.1).
        /// </summary>
        [Fact]
        public void MatrixVectorsMatch()
        {
            foreach (JsonElement testCase in Manifest.GetProperty("matrix").EnumerateArray())
            {
                string name = testCase.GetProperty("name").GetString();
                ParityCheckMatrix h = ParityCheckMatrix.Build(
                    testCase.GetProperty("k").GetInt32(),
                    testCase.GetProperty("r").GetInt32(),
                    testCase.GetProperty("n1").GetInt32(),
                    testCase.GetProperty("seed").GetInt32());

                Assert.True(testCase.GetProperty("entryCount").GetInt32() == h.EntryCount,
                    name + ": entry count");
                AssertBytesEqual(name, LoadBin(testCase.GetProperty("file").GetString()), h.Serialize());
            }
        }

        /// <summary>
        /// Encode vectors: load the <c>K</c> source symbols, encode, and assert the produced
        /// repair symbols equal the committed ones byte-for-byte (SPEC.md section 5).
        /// </summary>
        [Fact]
        public void EncodeVectorsMatch()
        {
            foreach (JsonElement testCase in Manifest.GetProperty("encode").EnumerateArray())
            {
                string name = testCase.GetProperty("name").GetString();
                var encodeCase = new EncodeCase(testCase);
                byte[][] symbols = encodeCase.SourceOnlySymbols();
                encodeCase.Codec.Encode(symbols);

                for (int p = 0; p < encodeCase.R; p++)
                {
                    AssertBytesEqual($"{name} repair[{p}]", encodeCase.Symbol(encodeCase.K + p),
                        symbols[encodeCase.K + p]);
                }

                Assert.True(encodeCase.Codec.Verify(symbols), name + ": Verify() must hold after encode");
            }
        }

        /// <summary>
        /// Decode vectors: start from the recorded present subset, decode, and assert the
        /// completion flag, the stage, the recovered count, the still-missing source indices, and
        /// the bytes of every symbol the decode claims to hold (SPEC.md section 6).
        /// </summary>
        [Fact]
        public void DecodeVectorsMatch()
        {
            var encodeCases = new Dictionary<string, JsonElement>();
            foreach (JsonElement testCase in Manifest.GetProperty("encode").EnumerateArray())
            {
                encodeCases[testCase.GetProperty("name").GetString()] = testCase;
            }

            foreach (JsonElement testCase in Manifest.GetProperty("decode").EnumerateArray())
            {
                string name = testCase.GetProperty("name").GetString();
                string reference = testCase.GetProperty("encodeCase").GetString();
                Assert.True(encodeCases.ContainsKey(reference), name + ": unknown encodeCase reference");
                var source = new EncodeCase(encodeCases[reference]);

                var present = new bool[source.N];
                for (int i = 0; i < source.N; i++)
                {
                    present[i] = true;
                }

                foreach (int index in IntArray(testCase.GetProperty("missing")))
                {
                    present[index] = false;
                }

                var symbols = new byte[source.N][];
                for (int i = 0; i < source.N; i++)
                {
                    if (present[i])
                    {
                        symbols[i] = source.Symbol(i);
                    }
                }

                DecodeResult result = source.Codec.Decode(symbols, present);

                Assert.True(testCase.GetProperty("expectComplete").GetBoolean() == result.IsComplete,
                    name + ": completion flag");
                Assert.True(ParseStage(testCase.GetProperty("expectStage").GetString()) == result.Stage,
                    name + ": stage (got " + result.Stage + ")");
                Assert.True(
                    testCase.GetProperty("expectRecoveredSymbols").GetInt32() == result.RecoveredSymbolCount,
                    name + ": recovered symbol count");
                Assert.True(
                    IntArray(testCase.GetProperty("expectMissingSource"))
                        .SequenceEqual(result.MissingSourceIndices()),
                    name + ": still-missing source indices");

                // Whatever the decode claims to hold must be the original bytes, whether it was
                // received, peeled, or solved.
                for (int i = 0; i < source.N; i++)
                {
                    if (present[i])
                    {
                        AssertBytesEqual($"{name} symbol[{i}]", source.Symbol(i), symbols[i]);
                    }
                }
            }
        }

        /// <summary>One encode case's parameters and committed symbol blobs.</summary>
        private sealed class EncodeCase
        {
            private readonly byte[] _sourceBlob;
            private readonly byte[] _repairBlob;
            private readonly int _symbolLength;

            internal readonly int K;
            internal readonly int R;
            internal readonly int N;
            internal readonly LdpcStaircaseCodec Codec;

            internal EncodeCase(JsonElement testCase)
            {
                K = testCase.GetProperty("k").GetInt32();
                R = testCase.GetProperty("r").GetInt32();
                N = K + R;
                _symbolLength = testCase.GetProperty("symbolLen").GetInt32();
                Codec = LdpcStaircaseCodec.Create(K, R, testCase.GetProperty("seed").GetInt32(),
                    testCase.GetProperty("n1").GetInt32());
                _sourceBlob = LoadBin(testCase.GetProperty("sourceBlob").GetString());
                _repairBlob = LoadBin(testCase.GetProperty("repairBlob").GetString());

                Assert.Equal(K * _symbolLength, _sourceBlob.Length);
                Assert.Equal(R * _symbolLength, _repairBlob.Length);
            }

            /// <summary>Symbol <paramref name="index"/> sliced out of the committed blobs.</summary>
            internal byte[] Symbol(int index)
            {
                byte[] blob = index < K ? _sourceBlob : _repairBlob;
                int offset = (index < K ? index : index - K) * _symbolLength;
                var symbol = new byte[_symbolLength];
                Array.Copy(blob, offset, symbol, 0, _symbolLength);
                return symbol;
            }

            /// <summary>An encode input: the <c>K</c> source symbols with empty repair slots.</summary>
            internal byte[][] SourceOnlySymbols()
            {
                var symbols = new byte[N][];
                for (int i = 0; i < K; i++)
                {
                    symbols[i] = Symbol(i);
                }

                return symbols;
            }
        }

        /// <summary>
        /// Byte-exact comparison with a precise diagnostic on the first differing offset — a
        /// vector mismatch indicates a real cross-language divergence, so the exact byte values
        /// are surfaced.
        /// </summary>
        private static void AssertBytesEqual(string label, byte[] expected, byte[] actual)
        {
            Assert.True(expected.Length == actual.Length,
                $"{label}: length mismatch - expected {expected.Length} bytes, got {actual.Length}");

            for (int i = 0; i < expected.Length; i++)
            {
                Assert.True(expected[i] == actual[i],
                    $"{label}: byte mismatch at offset {i} - expected 0x{expected[i]:x2}, "
                    + $"got 0x{actual[i]:x2}");
            }
        }
    }
}
